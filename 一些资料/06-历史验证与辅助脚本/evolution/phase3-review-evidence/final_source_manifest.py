import datetime
import json
import subprocess
from pathlib import Path

import run_review as R

root, out = R.ROOT, R.OUT
before = R.snapshot(['Platform', 'DataTransfer', 'Frontends'])
decoder = json.JSONDecoder()
fields = ['GoFiles', 'CgoFiles', 'CFiles', 'CXXFiles', 'MFiles', 'HFiles',
          'FFiles', 'SFiles', 'SwigFiles', 'SwigCXXFiles', 'SysoFiles',
          'EmbedFiles']
inputs = set()
commands = []
for module in ['Platform', 'DataTransfer']:
    argv = ['go', 'list', '-deps', '-test', '-json', './...']
    p = subprocess.run(argv, cwd=root / module, env=R.ENV, capture_output=True, text=True)
    (out / ('final-' + module.lower() + '-go-list.json')).write_text(p.stdout)
    (out / ('final-' + module.lower() + '-go-list.stderr.log')).write_text(p.stderr)
    assert p.returncode == 0, p.stderr
    commands.append({'module': module, 'argv': argv, 'exit_code': p.returncode})
    raw = p.stdout
    while raw.strip():
        raw = raw.lstrip()
        package, end = decoder.raw_decode(raw)
        raw = raw[end:]
        directory = Path(package.get('Dir', ''))
        for field in fields:
            for value in package.get(field, []):
                f = directory / value
                if f.is_file():
                    inputs.add(f)
        for data in [package.get('Module', {}), package.get('Module', {}).get('Replace', {})]:
            for f in [Path(data['GoMod'])] if data.get('GoMod') else []:
                if f.is_file():
                    inputs.add(f)
            if data.get('Dir'):
                for name in ['go.mod', 'go.sum']:
                    f = Path(data['Dir']) / name
                    if f.is_file():
                        inputs.add(f)
    for name in ['go.mod', 'go.sum']:
        inputs.add(root / module / name)
rows = [{'path': str(p), 'sha256': R.sha(p), 'bytes': p.stat().st_size} for p in sorted(inputs)]
after = R.snapshot(['Platform', 'DataTransfer', 'Frontends'])
changed = [p for p in before.keys() | after.keys() if before.get(p) != after.get(p)]
toolchain = subprocess.check_output(['go', 'env', '-json', 'GOVERSION', 'GOOS', 'GOARCH', 'CGO_ENABLED', 'GOEXPERIMENT'], cwd=root/'Platform', env=R.ENV, text=True)
current = {'recorded_at': datetime.datetime.now(datetime.timezone.utc).isoformat(),
           'commands': commands, 'toolchain': json.loads(toolchain),
           'inputs': rows, 'changed_during_manifest': changed,
           'method': 'Fresh go list -deps -test -json ./... for both backend modules; hashes of the actual package GoFiles (including generated test variants), cgo, assembly, embeds, and module metadata include standard library and module dependencies. Dependency TestGoFiles/XTestGoFiles are not added separately because dependency tests are not compiled by these commands. Generated test-main files without a persistent file path are generated by Go from these inputs.'}
R.json_write(out / 'final-compiled-inputs.json', current)
full = json.loads((out / 't02-platform-full.metadata.json').read_text())
front = json.loads((out / 'c05-frontend-production-build.metadata.json').read_text())
tested = dict(full['source_after'])
tested.update({p: h for p, h in front['source_after'].items() if p.startswith('Frontends/')})
mismatches = [p for p, h in tested.items() if not (root/p).is_file() or R.sha(root/p) != h]
manifest = {'recorded_at': current['recorded_at'], 'files': tested,
            'backend_test_metadata': str((out/'t02-platform-full.metadata.json').relative_to(root)),
            'frontend_build_metadata': str((out/'c05-frontend-production-build.metadata.json').relative_to(root)),
            'source_changes_after_checks': mismatches,
            'source_count': len(tested), 'compiled_input_count': len(rows)}
R.json_write(out / 'final-reviewed-source.json', manifest)
assert not changed and not mismatches
print(json.dumps({'compiled_inputs': len(rows), 'source_count': len(tested),
                  'source_mismatches': mismatches, 'changes_during_manifest': changed}))
